def employer_i18n(request):
    lang = get_lang(request)
    wallet_total = None
    if getattr(request.user, "is_authenticated", False):
        # Import locally so this lightweight template context stays usable at startup.
        from .economy import get_or_create_wallet

        wallet_total = get_or_create_wallet(request.user).total_credits
        from .chat_api import _unread_counts
        from .models import ChatConversation, EmployerBoardPublishingAuthorization

        conversations = list(
            ChatConversation.objects.filter(employer=request.user, last_message_at__isnull=False).only(
                "id", "candidate_id", "employer_id", "candidate_last_read_at", "employer_last_read_at"
            )
        )
        chat_unread_count = sum(_unread_counts(conversations, request.user).values())
        board_publishing_pending = EmployerBoardPublishingAuthorization.objects.filter(
            employer=request.user,
            status="pending",
        ).exists()
    else:
        chat_unread_count = 0
        board_publishing_pending = False
    support_workspace_available = False
    support_header = {
        "organization_id": "",
        "query": "",
        "active": {},
        "workers": False,
        "requests": False,
        "registries": False,
        "staff_chats": False,
        "time": False,
        "transport": False,
        "fleet": False,
        "team": False,
    }
    if getattr(request.user, "is_authenticated", False):
        # The link is intentionally absent until Support is enabled and the
        # account belongs to an active, manually approved organization.
        from support.feature_flags import is_support_feature_enabled

        if is_support_feature_enabled():
            from support.models import OrganizationMembership
            from support.permission_codes import (
                CHAT_MANAGE,
                HOUSING_MANAGE,
                ORGANIZATION_MANAGE,
                REQUEST_DECIDE,
                SCHEDULE_MANAGE,
                TIME_VIEW,
                TRANSPORT_MANAGE,
                WORKER_VIEW,
            )
            from support.permissions import has_permission

            memberships = list(
                OrganizationMembership.objects.filter(
                    user=request.user,
                    state=OrganizationMembership.STATE_ACTIVE,
                    organization__status="active",
                )
                .select_related("organization")
                .order_by("organization__display_name", "id")
            )
            support_workspace_available = bool(memberships)
            if memberships:
                requested_organization_id = (request.GET.get("organization") or "").strip()
                membership = next(
                    (
                        item
                        for item in memberships
                        if str(item.organization.public_id) == requested_organization_id
                    ),
                    memberships[0],
                )
                organization = membership.organization
                resolver_match = getattr(request, "resolver_match", None)
                resolver_namespace = getattr(resolver_match, "namespace", "")
                resolver_name = getattr(resolver_match, "url_name", "")
                support_header = {
                    "organization_id": str(organization.public_id),
                    "query": f"organization={organization.public_id}",
                    "active": {
                        "workers": resolver_namespace == "support"
                        and resolver_name in {"workspace", "worker-card"},
                        "projects": resolver_namespace == "support"
                        and resolver_name in {"projects", "project-detail"},
                        "requests": resolver_namespace == "support"
                        and resolver_name == "worker-requests",
                        "registries": resolver_namespace == "support"
                        and resolver_name == "registries",
                        "fleet": resolver_namespace == "support"
                        and resolver_name == "fleet",
                        "staff_chats": resolver_namespace == "support"
                        and resolver_name in {"conversations", "conversation-detail"},
                        "general_chat": resolver_namespace == "employer"
                        and resolver_name in {"chat_list", "chat_detail"},
                    },
                    "workers": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=WORKER_VIEW,
                    ),
                    "projects": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=SCHEDULE_MANAGE,
                    ),
                    "requests": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=REQUEST_DECIDE,
                    ),
                    "registries": any(
                        has_permission(
                            user=request.user,
                            organization=organization,
                            permission_code=code,
                        )
                        for code in (HOUSING_MANAGE, SCHEDULE_MANAGE, TRANSPORT_MANAGE)
                    ),
                    "staff_chats": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=CHAT_MANAGE,
                    ),
                    "time": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=TIME_VIEW,
                    ),
                    "transport": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=TRANSPORT_MANAGE,
                    ),
                    "fleet": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=TRANSPORT_MANAGE,
                    ),
                    "team": has_permission(
                        user=request.user,
                        organization=organization,
                        permission_code=ORGANIZATION_MANAGE,
                    ),
                }
    return {
        "employer_t": t(lang),
        "employer_wallet_total": wallet_total,
        "employer_chat_unread_count": chat_unread_count,
        "employer_board_publishing_pending": board_publishing_pending,
        "employer_support_workspace_available": support_workspace_available,
        "employer_support_header": support_header,
        # Language changes must return a manager to the same Support section,
        # including the active organization filter.
        "employer_language_next": request.get_full_path(),
        "employer_languages": [
            {
                "code": code,
                "label": LANGUAGE_NAMES.get(code, code.upper()),
                "active": code == lang,
            }
            for code in SUPPORTED_LANGS
        ],
    }


def apply_language_cookie(response, lang):
    response.set_cookie(
        LANG_COOKIE,
        normalize_lang(lang),
        max_age=60 * 60 * 24 * 365,
        samesite="Lax",
    )
    return response


def tr(request, key, default=None):
    return t(get_lang(request)).get(key, default if default is not None else key)


